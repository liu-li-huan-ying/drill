// 打卡印记（P2.2「打卡日历印章化」）：一个打卡日 = 一枚朱印。
//
// ── 三代方案的取舍（每一代都是被上一代的实测结果否掉的）
//
// 第一代「印面递增」：按当日学习量把印面从 6dp 递到 10.8dp。
//   主人的反驳一句到位：「大小绝对是要一样大的，不然大大小小放一起很不好看」。
//   背后有一条比「好不好看」更硬的编码原则：**重复出现、且必须并排比较的元素，
//   不能用尺寸编码差异**。日历里 30 个格子是一排读数，尺寸一多样，眼睛去比的就是
//   「哪个更大」，而不是「哪天的量更多」；何况相邻两档只差 1.6dp，比大小本身也不成立。
//
// 第二代「同尺寸、墨量三档」（细边朱文 / 粗边朱文 / 满墨白文）：尺寸恒定对了，
//   但在 9dp 印面上只有 1dp 的差别，主人反馈「小框有点小」—— 实测整屏里三档根本分不出。
//   **读不出来的分辨率不是分辨率，是噪声。**
//
// 第三代（现行）「同尺寸、印面完整度三档」：把印面放大到 22dp，复用完成屏那枚
//   「今日已毕」章的形制（朱底 + 纸色内框 + 一个纸色的字），用**印面被磨损的程度**表浓度。
//
// ── 为什么只有「一处伤口」，而不是撒一堆细节
// 曾试过「断框 + 麻点 + 残字 + 两处缺角」一起上：单枚拿在手里看是「有细节」，
// 30 枚并排就是**一片脏**。更关键的是 L1（背得最少）恰恰是**最常见**的那一档 ——
// 多数日子背得不多，所以最常见的那一档必须是最好看的那一档，不能是一团被啃烂的红。
// 故收敛成一条规矩：**一处伤口，三个深度**（右下一角，随档位变深），剪影始终是方印。
//   1 少 · 斑驳战损：缺角深到咬穿内框的角、并蹭掉「毕」的右下
//   2 中 · 稍斑驳残缺：缺角只到印边
//   3 多 · 完美无瑕：四角齐全
// 同一种手法（缺角）用三个量级表达，阶梯才立得住 —— 三种不同手法各表达一档，
// 读者要学三次，还学不出「哪个更多」。
//
// ── 为什么 22dp 是上限而不是随便挑的
// 日历列宽是 `SPACE.touch` 48dp，窄屏（320dp 宽）时卡片内可用约 35dp，
// 22dp 的印面两侧各留 6.5dp，相邻两枚相隔 13dp —— 再大一档就会在窄屏上挤到贴边。
//
// `slot` 是印记槽的高度：印记有无都占住这个高度，日历的行高才不会随打卡情况跳动。
// `char` 是印面上的那一个字。**「今日已毕」四个字在 22dp 上放不下**（每字不足 5dp），
// 只能简化为一个字；取「毕」是让日历里的每一枚印都直接指向完成屏那枚章。
export const STAMP = { size: 22, slot: 24, char: '毕' } as const;

/**
 * 印面完整度档位（1..3）：同尺寸下印面被磨损的程度。见上方 STAMP 注释。
 * 0 不在此类型里 —— 未打卡就**不画印**（日历里 30 个空槽描一圈虚线等于凭空多 30 个元素，
 * 空白的克制本身就是「还没盖」的表达）。
 */
export type SealWear = 1 | 2 | 3;

/**
 * 当日学习量 → 印面完整度档（1..3）。返回 0 表示这天没打卡。
 *
 * 分档放在令牌层而不是屏幕里：日历格与图例必须用**同一条**规则。
 * 图例本来就只是「三档的样本」——规则一旦散成两处，图例就会和日历说不同的话，
 * 而图例的全部意义正是「不用反查」。
 */
export function sealWear(total: number, max: number): SealWear | 0 {
  if (total <= 0 || max <= 0) return 0;
  const lv = Math.ceil((total / max) * 3);
  if (lv <= 1) return 1;
  if (lv === 2) return 2;
  return 3;
}

