// 动效曲线：**唯一来源**。曲线以贝塞尔控制点的形式导出（四个数），
// 用的时候 `Easing.bezier(...EASE)` —— 这样本文件仍然零依赖，而全项目只有两条曲线。
//
// 为什么必须收敛到两条：动效的廉价感八成来自「每条动效各用一个 ease」——
// 页面用 inOut、按钮用默认、印章用另一个，它们单看都还行，放在一起就散。
// 纸与墨的动作只有三种，每一种对应一个**物理情境**：
//   EASE        主曲线：起步快、收尾长 —— 东西被推了一下，自己减速停住（无过冲，纸不会弹）。
//   EASE_SETTLE 落印曲线：起步更急、收尾更缓 —— 印章落下只有一次，要「啪」地定住。
//   EASE_FALL   落体曲线：**起步慢、收尾快**，即加速。
//               它与 EASE 方向恰好相反，而这不是风格选择：EASE 描述的是「被人推了一下的
//               东西，外力已经撤走，所以只会越来越慢」；印章的下落段是**重力**在做事，
//               它只会越来越快。用减速曲线画下落，观众读到的是「有人把章轻轻放下去」，
//               而不是「章落下来」—— 落印于是彻底失去冲击力。
//
// 曲线的「回弹」一律不再由插值停点承担（2026-09-18 推翻旧结论）：
// 旧版把 `stamp` 0→1 交给一条 EASE_SETTLE，再用停点 [0, .72, .88, 1] 表达
// 「落 / 触纸 / 回弹 / 定住」。急收曲线前 20% 的时间就走完约 80% 路程，
// 于是这些停点全挤进最后几十毫秒，肉眼只剩「抖了一下」（详见 MOTION 里 sealFall 的注释）。
// **一条曲线只能塑造一段动作的形状，不能承载一条时间轴** —— 分段必须是多段独立 duration。
